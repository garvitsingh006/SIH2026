class Sen2VenusDataset(Dataset):

    def __init__(self, taco_dataset, indices):
        self.dataset = taco_dataset
        self.indices = indices

    def __len__(self):
        return len(self.indices)

    def __getitem__(self, i):

        idx = self.indices[i]

        row = self.dataset.read(idx)

        lr_path = row.read(0)
        hr_path = row.read(1)

        # Read LR: 10 bands, 128×128
        with rio.open(lr_path) as src:
            lr = src.read().astype(np.float32)

        # Read HR: 8 bands, 256×256
        with rio.open(hr_path) as src:
            hr = src.read().astype(np.float32)

        # Convert uint16 reflectance values
        lr /= 10000.0
        hr /= 10000.0

        # PyTorch tensors: [C,H,W]
        lr = torch.from_numpy(lr)
        hr = torch.from_numpy(hr)

        return lr, hr

