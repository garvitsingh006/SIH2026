for epoch in range(gan_epochs):

    generator.train()
    discriminator.train()
    g_loss_total = d_loss_total = pixel_loss_total = adv_loss_total = fm_loss_total = 0.0
    epoch_start = time.time()

    for batch_idx, (lr_img, hr_img) in enumerate(train_loader):
        lr_img = lr_img.to(device, non_blocking=True)
        hr_img = hr_img.to(device, non_blocking=True)

        # ---------------- Discriminator step ----------------
        d_optimizer.zero_grad()
        with torch.no_grad():
            fake_hr = generator(lr_img)
        real_logits = discriminator(hr_img)
        fake_logits = discriminator(fake_hr.detach())
        d_loss = d_ragan_loss(real_logits, fake_logits)        # CHANGE 1
        d_loss.backward()
        d_optimizer.step()

        # ---------------- Generator step ----------------
        g_optimizer.zero_grad()
        fake_hr = generator(lr_img)
        fake_logits, fake_feats = discriminator(fake_hr, return_features=True)   # CHANGE 4
        with torch.no_grad():
            real_logits_g, real_feats = discriminator(hr_img, return_features=True)  # CHANGE 4 (fixed reference)

        pixel_loss = pixel_criterion(fake_hr, hr_img)
        adv_loss = g_ragan_loss(real_logits_g, fake_logits)     # CHANGE 1
        fm_loss = sum(
            F.l1_loss(f, r) for f, r in zip(fake_feats, real_feats)
        ) / len(fake_feats)                                     # CHANGE 4

        g_loss = pixel_loss + adv_weight * adv_loss + fm_weight * fm_loss
        g_loss.backward()
        g_optimizer.step()

        g_loss_total += g_loss.item()
        d_loss_total += d_loss.item()
        pixel_loss_total += pixel_loss.item()
        adv_loss_total += adv_loss.item()
        fm_loss_total += fm_loss.item()

        if (batch_idx + 1) % 10 == 0:
            with torch.no_grad():
                real_conf = torch.sigmoid(real_logits).mean().item()
                fake_conf = torch.sigmoid(fake_logits).mean().item()
            print(f"  Epoch {epoch+1}/{gan_epochs} | Batch {batch_idx+1}/{len(train_loader)} | "
                  f"G: {g_loss.item():.6f} (pix {pixel_loss.item():.6f} + adv {adv_loss.item():.6f} + fm {fm_loss.item():.6f}) | "
                  f"D: {d_loss.item():.6f} | D(real): {real_conf:.3f} D(fake): {fake_conf:.3f}")

    g_loss_total /= len(train_loader)
    d_loss_total /= len(train_loader)
    pixel_loss_total /= len(train_loader)
    adv_loss_total /= len(train_loader)
    fm_loss_total /= len(train_loader)

    generator.eval()
    val_loss = 0.0
    with torch.no_grad():
        for lr_img, hr_img in val_loader:
            lr_img, hr_img = lr_img.to(device), hr_img.to(device)
            pred = generator(lr_img)
            val_loss += pixel_criterion(pred, hr_img).item()
    val_loss /= len(val_loader)
    epoch_time = time.time() - epoch_start

    if val_loss < best_this_run_val_loss:
        best_this_run_val_loss = val_loss
        best_this_run_epoch = epoch + 1
        torch.save(generator.state_dict(), RUN_CHECKPOINT_PATH)
        status = " ⭐ new best THIS RUN — saved"
        epochs_since_improvement = 0                            # CHANGE 5
    else:
        status = ""
        epochs_since_improvement += 1                            # CHANGE 5

    if val_loss < global_best_val_loss:
        global_best_val_loss = val_loss
        save_global_best(generator, val_loss, RUN_CHECKPOINT_PATH if os.path.exists(RUN_CHECKPOINT_PATH) else None)
        status += " 🌍 NEW GLOBAL BEST"

    print(f"\nEpoch {epoch+1}/{gan_epochs} COMPLETE | "
          f"Avg G: {g_loss_total:.6f} (pix {pixel_loss_total:.6f} + adv*{adv_weight} {adv_loss_total:.6f} + fm*{fm_weight} {fm_loss_total:.6f}) | "
          f"Avg D: {d_loss_total:.6f} | Val Pixel Loss: {val_loss:.6f} | "
          f"This-run best: {best_this_run_val_loss:.6f} (epoch {best_this_run_epoch}) | "
          f"Global best: {global_best_val_loss:.6f} | Time: {epoch_time:.1f}s{status}\n")

    if epochs_since_improvement >= patience:                     # CHANGE 5
        print(f"Early stopping: no improvement for {patience} epochs.")
        break

