d_optimizer = torch.optim.Adam(discriminator.parameters(), lr=2e-4, betas=(0.9, 0.999))

adv_weight = 0.0005   # CHANGE 3: smaller than your last two runs
fm_weight = 1.0        # CHANGE 4: feature-matching weight

print(f"[Setup] Generator LR: {g_optimizer.param_groups[0]['lr']} | "
      f"Discriminator LR: {d_optimizer.param_groups[0]['lr']} | "
      f"adv_weight: {adv_weight} | fm_weight: {fm_weight}")


# --------------------------------------------
# CHANGE 1: RaGAN loss helpers
# --------------------------------------------

def d_ragan_loss(real_logits, fake_logits):
    real_rel = real_logits - fake_logits.mean(0, keepdim=True)
    fake_rel = fake_logits - real_logits.mean(0, keepdim=True)
    return 0.5 * (
        adv_criterion(real_rel, torch.ones_like(real_rel)) +
        adv_criterion(fake_rel, torch.zeros_like(fake_rel))
    )

def g_ragan_loss(real_logits, fake_logits):
    real_rel = real_logits - fake_logits.mean(0, keepdim=True)
    fake_rel = fake_logits - real_logits.mean(0, keepdim=True)
    return 0.5 * (
        adv_criterion(real_rel, torch.zeros_like(real_rel)) +
        adv_criterion(fake_rel, torch.ones_like(fake_rel))
    )


