class Discriminator(nn.Module):

    def __init__(self, in_channels=8, features=64):
        super().__init__()

        def block(in_c, out_c, stride):
            return [
                nn.utils.spectral_norm(                       # CHANGE 2: spectral norm
                    nn.Conv2d(in_c, out_c, 3, stride=stride, padding=1)
                ),
                nn.LeakyReLU(0.2, inplace=True)
                # NOTE: InstanceNorm2d removed — spectral norm replaces it
            ]

        self.model = nn.ModuleList([                          # ModuleList so we can walk layers for feature matching
            *block(in_channels, features, 1),
            *block(features, features, 2),
            *block(features, features * 2, 1),
            *block(features * 2, features * 2, 2),
            *block(features * 2, features * 4, 1),
            *block(features * 4, features * 4, 2),
            nn.utils.spectral_norm(
                nn.Conv2d(features * 4, 1, 3, padding=1)
            )  # patch logits
        ])

    def forward(self, x, return_features=False):               # CHANGE 4: feature matching support
        feats = []
        h = x
        for layer in self.model:
            h = layer(h)
            if return_features and isinstance(layer, nn.LeakyReLU):
                feats.append(h)
        return (h, feats) if return_features else h


discriminator = Discriminator(in_channels=8).to(device)

adv_criterion = nn.BCEWithLogitsLoss()
pixel_criterion = criterion

# CHANGE 3: TTUR — wider G/D LR gap
