class SpectralLoss(nn.Module):

    def __init__(
        self,
        mse_weight=1.0,
        spectral_weight=0.1,
        gradient_weight=0.05
    ):
        super().__init__()

        self.mse_weight = mse_weight
        self.spectral_weight = spectral_weight
        self.gradient_weight = gradient_weight

    def forward(self, prediction, target):

        # Pixel reconstruction
        mse = torch.mean(
            (prediction - target) ** 2
        )

        # Spectral consistency
        pred_mean = prediction.mean(
            dim=1, keepdim=True
        )

        target_mean = target.mean(
            dim=1, keepdim=True
        )

        pred_spectral = prediction - pred_mean
        target_spectral = target - target_mean

        spectral = torch.mean(
            (pred_spectral - target_spectral) ** 2
        )

        # Spatial gradients
        pred_dx = (
            prediction[:, :, :, 1:]
            - prediction[:, :, :, :-1]
        )

        target_dx = (
            target[:, :, :, 1:]
            - target[:, :, :, :-1]
        )

        pred_dy = (
            prediction[:, :, 1:, :]
            - prediction[:, :, :-1, :]
        )

        target_dy = (
            target[:, :, 1:, :]
            - target[:, :, :-1, :]
        )

        gradient = (
            torch.mean(torch.abs(pred_dx - target_dx))
            +
            torch.mean(torch.abs(pred_dy - target_dy))
        )

        return (
            self.mse_weight * mse
            + self.spectral_weight * spectral
            + self.gradient_weight * gradient
        )


