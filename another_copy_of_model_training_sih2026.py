import torch
import torch.nn as nn
import torch.nn.functional as F


class ResidualBlock(nn.Module):

    def __init__(self, channels):
        super().__init__()

        self.conv1 = nn.Conv2d(
            channels, channels, 3, padding=1
        )

        self.conv2 = nn.Conv2d(
            channels, channels, 3, padding=1
        )

        self.relu = nn.ReLU(inplace=True)

    def forward(self, x):

        residual = self.relu(self.conv1(x))
        residual = self.conv2(residual)

        return x + residual


class ResidualGroup(nn.Module):

    def __init__(self, channels, num_blocks=4):
        super().__init__()

        self.blocks = nn.Sequential(
            *[
                ResidualBlock(channels)
                for _ in range(num_blocks)
            ]
        )

        self.conv = nn.Conv2d(
            channels, channels, 3, padding=1
        )

    def forward(self, x):

        residual = self.blocks(x)
        residual = self.conv(residual)

        return x + residual


class TransformerBlock(nn.Module):

    def __init__(
        self,
        channels,
        num_heads=8,
        window_size=8,
        shift_size=0,
        mlp_ratio=2
    ):
        super().__init__()

        self.window_size = window_size
        self.shift_size = shift_size

        self.norm1 = nn.LayerNorm(channels)

        self.attention = nn.MultiheadAttention(
            embed_dim=channels,
            num_heads=num_heads,
            batch_first=True
        )

        self.norm2 = nn.LayerNorm(channels)

        hidden = channels * mlp_ratio

        self.mlp = nn.Sequential(
            nn.Linear(channels, hidden),
            nn.GELU(),
            nn.Linear(hidden, channels)
        )

    def forward(self, x):

        B, C, H, W = x.shape
        ws = self.window_size
        ss = self.shift_size

        # ----------------------------------------
        # Shift feature map
        # ----------------------------------------

        if ss > 0:
            x = torch.roll(
                x,
                shifts=(-ss, -ss),
                dims=(2, 3)
            )

        # ----------------------------------------
        # Split into windows
        # ----------------------------------------

        x = x.view(
            B,
            C,
            H // ws,
            ws,
            W // ws,
            ws
        )

        x = x.permute(
            0, 2, 4, 3, 5, 1
        ).contiguous()

        # [B, number_of_windows, ws*ws, C]

        x = x.view(
            B,
            (H // ws) * (W // ws),
            ws * ws,
            C
        )

        # Merge windows into batch dimension

        x = x.view(
            -1,
            ws * ws,
            C
        )

        # ----------------------------------------
        # Self attention
        # ----------------------------------------

        residual = x

        x_norm = self.norm1(x)

        attention_out, _ = self.attention(
            x_norm,
            x_norm,
            x_norm
        )

        x = residual + attention_out

        # ----------------------------------------
        # MLP
        # ----------------------------------------

        residual = x

        x = residual + self.mlp(
            self.norm2(x)
        )

        # ----------------------------------------
        # Restore windows
        # ----------------------------------------

        x = x.view(
            B,
            H // ws,
            W // ws,
            ws,
            ws,
            C
        )

        x = x.permute(
            0, 5, 1, 3, 2, 4
        ).contiguous()

        x = x.view(
            B,
            C,
            H,
            W
        )

        # ----------------------------------------
        # Reverse shift
        # ----------------------------------------

        if ss > 0:
            x = torch.roll(
                x,
                shifts=(ss, ss),
                dims=(2, 3)
            )

        return x


class CNNTransformerSR(nn.Module):

    def __init__(
        self,
        in_channels=10,
        out_channels=8,
        features=96,
        num_groups=4,
        blocks_per_group=4,
        transformer_blocks=2
    ):
        super().__init__()

        # ========================================
        # CNN HEAD
        # ========================================

        self.head = nn.Conv2d(
            in_channels,
            features,
            3,
            padding=1
        )

        # ========================================
        # CNN FEATURE EXTRACTION
        # ========================================

        self.cnn_body = nn.Sequential(
            *[
                ResidualGroup(
                    features,
                    blocks_per_group
                )
                for _ in range(num_groups)
            ],

            nn.Conv2d(
                features,
                features,
                3,
                padding=1
            )
        )

        # ========================================
        # TRANSFORMER
        # ========================================

        self.transformer = nn.Sequential(
              TransformerBlock(
                  features,
                  num_heads=8,
                  window_size=8,
                  shift_size=0,
                  mlp_ratio=2
              ),

              TransformerBlock(
                  features,
                  num_heads=8,
                  window_size=8,
                  shift_size=4,
                  mlp_ratio=2
              )
          )

        # ========================================
        # FUSION
        # ========================================

        self.fusion = nn.Conv2d(
            features,
            features,
            3,
            padding=1
        )

        # ========================================
        # 2× UPSAMPLING
        # ========================================

        self.upsample = nn.Sequential(

            nn.Conv2d(
                features,
                features * 4,
                3,
                padding=1
            ),

            nn.PixelShuffle(2),

            nn.ReLU(inplace=True)
        )

        # ========================================
        # OUTPUT
        # ========================================

        self.tail = nn.Conv2d(
            features,
            out_channels,
            3,
            padding=1
        )

        # ========================================
        # BICUBIC SKIP
        # ========================================

        self.skip = nn.Conv2d(
            in_channels,
            out_channels,
            1
        )

    def forward(self, x):

        # CNN features
        features = self.head(x)

        cnn_features = self.cnn_body(features)

        features = features + cnn_features

        # Transformer global attention
        transformer_features = self.transformer(
            features
        )

        features = features + transformer_features

        # Fusion
        features = self.fusion(features)

        # Upsample
        features = self.upsample(features)

        # Predict HR spectral bands
        output = self.tail(features)

        # Bicubic baseline
        skip = self.skip(x)

        skip = F.interpolate(
            skip,
            scale_factor=2,
            mode="bicubic",
            align_corners=False
        )

        return output + skip

